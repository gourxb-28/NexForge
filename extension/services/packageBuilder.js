window.NexForge = window.NexForge || {};
window.NexForge.services = window.NexForge.services || {};

window.NexForge.services.packageBuilder = {
  
  buildPackage: (normalizedData, contextObject, compressionResult, compressionMode) => {
    if (!normalizedData || !contextObject || !compressionResult) {
      throw new Error("Missing required data to build context package.");
    }

    const timestamp = new Date().toISOString();
    
    let safeTitle = (normalizedData.conversationTitle || 'untitled').toLowerCase();
    safeTitle = safeTitle.replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)+/g, '');
    const filenameBase = `nexforge-${safeTitle}-${timestamp.split('T')[0]}`;

    const cbp = {
      manifest: {
        format: "ContextBridgePackage",
        version: "1.0.0",
        exportDate: timestamp,
        generator: "NexForge Extension"
      },
      metadata: {
        sourcePlatform: normalizedData.sourcePlatform,
        conversationTitle: normalizedData.conversationTitle,
        compressionMode: compressionMode,
        messageCount: normalizedData.metadata.normalizedCount,
        promptLength: compressionResult.charCount
      },
      structuredContext: {
        goal: Array.from(contextObject.overview || []),
        techStack: Array.from(contextObject.techStack || []),
        requirements: Array.from(contextObject.requirements || []),
        constraints: Array.from(contextObject.constraints || []),
        architecture: Array.from(contextObject.architecture || []),
        decisions: Array.from(contextObject.decisions || []),
        completedWork: Array.from(contextObject.completedWork || []),
        errors: Array.from(contextObject.errors || []),
        pendingTasks: Array.from(contextObject.pendingTasks || []),
        nextStep: contextObject.nextStep || ""
      },
      continuationPrompt: compressionResult.text,
      history: normalizedData.messages,
      exportFiles: {
        jsonFilename: `${filenameBase}.json`,
        markdownFilename: `${filenameBase}.md`,
        txtFilename: `${filenameBase}.txt`
      }
    };

    return cbp;
  },

  toMarkdown: (cbp) => {
    let md = `> This context package was generated by **NexForge** on ${new Date(cbp.manifest.exportDate).toLocaleString()}.\n\n`;
    md += `> **Source Platform:** ${cbp.metadata.sourcePlatform}\n`;
    md += `> **Compression Mode:** ${cbp.metadata.compressionMode}\n\n`;
    md += `---\n\n`;
    md += cbp.continuationPrompt;
    return md;
  },

  
  toPlainText: (cbp) => {
    let txt = `[NexForge Context Package]\n`;
    txt += `Generated: ${new Date(cbp.manifest.exportDate).toLocaleString()}\n`;
    txt += `Source: ${cbp.metadata.sourcePlatform}\n`;
    txt += `Mode: ${cbp.metadata.compressionMode}\n`;
    txt += `----------------------------------------\n\n`;
    txt += cbp.continuationPrompt;
    return txt;
  }
};
